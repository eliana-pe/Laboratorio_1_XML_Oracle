-- Esquema de trabajo: HR

SELECT
    USER AS USUARIO,
    SYS_CONTEXT('USERENV', 'CON_NAME') AS CONTENEDOR,
    (SELECT COUNT(*) FROM EMPLOYEES) AS EMPLEADOS,
    (SELECT COUNT(*) FROM DEPARTMENTS) AS DEPARTAMENTOS,
    (SELECT COUNT(*) FROM JOBS) AS CARGOS
FROM DUAL;
